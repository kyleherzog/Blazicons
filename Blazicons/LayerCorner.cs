namespace Blazicons;

/// <summary>
/// Specifies the corner at which a counter badge overlay is anchored.
/// </summary>
public enum LayerCorner
{
    /// <summary>
    /// The top-right corner.
    /// </summary>
    TopRight,

    /// <summary>
    /// The bottom-right corner.
    /// </summary>
    BottomRight,

    /// <summary>
    /// The bottom-left corner.
    /// </summary>
    BottomLeft,

    /// <summary>
    /// The top-left corner.
    /// </summary>
    TopLeft,
}